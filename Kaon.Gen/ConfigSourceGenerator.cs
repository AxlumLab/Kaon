using System.Collections.Generic;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

namespace NetGen;

public readonly struct ConfigNodeInfo(string memberName, string memberType, string key, string serializerType)
{
    public string MemberName { get; } = memberName;
    public string MemberType { get; } = memberType;
    public string Key { get; } = key;
    public string SerializerType { get; } = serializerType;
}

public readonly struct ConfigInfo(string fileName, string backendType, int version)
{
    public string FileName { get; } = fileName;
    public string BackendType { get; } = backendType;
    public int Version { get; } = version;
}

public sealed class ConfigReceiver : ISyntaxReceiver
{
    public List<ClassDeclarationSyntax> Candidates { get; } = new();

    public void OnVisitSyntaxNode(SyntaxNode node)
    {
        if (node is not ClassDeclarationSyntax cls)
            return;

        if (cls.AttributeLists
            .SelectMany(static list => list.Attributes)
            .Any(static attr => attr.Name.ToString().Contains("Config")))
        {
            Candidates.Add(cls);
        }
    }
}

[Generator]
public sealed class ConfigSourceGenerator : ISourceGenerator
{
    public void Initialize(GeneratorInitializationContext context)
    {
        context.RegisterForSyntaxNotifications(static () => new ConfigReceiver());
    }

    public void Execute(GeneratorExecutionContext context)
    {
        if (context.SyntaxReceiver is not ConfigReceiver receiver)
            return;

        foreach (var cls in receiver.Candidates)
        {
            var model = context.Compilation.GetSemanticModel(cls.SyntaxTree);
            if (model.GetDeclaredSymbol(cls) is not INamedTypeSymbol classSymbol)
                continue;

            if (!HasAttribute(classSymbol, "ConfigAttribute"))
                continue;

            var configInfo = GetConfigInfo(classSymbol);
            var nodes = CollectConfigNodes(classSymbol);
            var source = Generate(classSymbol, configInfo, nodes);
            context.AddSource($"{classSymbol.Name}.Config.g.cs", source);
        }
    }

    private static string Generate(INamedTypeSymbol classSymbol, ConfigInfo configInfo, IReadOnlyList<ConfigNodeInfo> nodes)
    {
        var ns = classSymbol.ContainingNamespace.IsGlobalNamespace
            ? ""
            : classSymbol.ContainingNamespace.ToDisplayString();

        var builder = new StringBuilder();
        builder.AppendLine("// <auto-generated />");
        builder.AppendLine("#nullable enable");
        builder.AppendLine("using System.Threading.Tasks;");
        builder.AppendLine("using Kaon.Config;");
        if (ns.Length > 0)
        {
            builder.Append("namespace ").Append(ns).AppendLine(";");
            builder.AppendLine();
        }

        builder.Append("public partial class ").Append(classSymbol.Name)
            .AppendLine(" : global::Kaon.Config.IConfig, global::Kaon.Config.IGeneratedConfigMetadata");
        builder.AppendLine("{");
        builder.Append("    public string? ConfigFileName => ");
        builder.Append(configInfo.FileName.Length == 0 ? "null" : $"\"{EscapeString(configInfo.FileName)}\"");
        builder.AppendLine(";");
        builder.AppendLine();
        builder.Append("    public int ConfigVersion => ").Append(configInfo.Version).AppendLine(";");
        builder.AppendLine();
        builder.Append("    public global::Kaon.Config.IConfigBackend? CreateBackend() => ");
        builder.Append(configInfo.BackendType.Length == 0 ? "null" : $"new {configInfo.BackendType}()");
        builder.AppendLine(";");
        builder.AppendLine();
        builder.AppendLine("    public void RegisterSerializers(global::Kaon.Config.ConfigSerializerRegistry registry)");
        builder.AppendLine("    {");
        foreach (var node in nodes)
        {
            if (node.SerializerType.Length == 0)
                continue;

            builder.Append("        registry.Register<").Append(node.MemberType).Append(">(\"")
                .Append(EscapeString(node.Key)).Append("\", new ").Append(node.SerializerType).AppendLine("());");
        }
        builder.AppendLine("    }");
        builder.AppendLine();
        builder.AppendLine("    public global::System.Threading.Tasks.Task OnProcessing(global::Kaon.Config.ConfigFactory manager)");
        builder.AppendLine("    {");

        foreach (var node in nodes)
        {
            var escapedMember = EscapeIdentifier(node.MemberName);
            var escapedKey = EscapeString(node.Key);
            builder.Append("        var ").Append(escapedMember).Append("Value = this.").Append(escapedMember).AppendLine(";");
            builder.Append("        manager.ProcessField(\"").Append(escapedKey).Append("\", ref ").Append(escapedMember).AppendLine("Value);");
            builder.Append("        this.").Append(escapedMember).Append(" = ").Append(escapedMember).AppendLine("Value;");
        }

        builder.AppendLine("        return global::System.Threading.Tasks.Task.CompletedTask;");
        builder.AppendLine("    }");
        builder.AppendLine("}");
        return builder.ToString();
    }

    private static List<ConfigNodeInfo> CollectConfigNodes(INamedTypeSymbol classSymbol)
    {
        var nodes = new List<ConfigNodeInfo>();
        foreach (var member in classSymbol.GetMembers())
        {
            switch (member)
            {
                case IFieldSymbol field when !field.IsStatic && !field.IsReadOnly:
                    if (TryGetConfigNode(field, out var fieldKey, out var fieldSerializer))
                    {
                        var key = fieldKey.Length == 0 ? field.Name : fieldKey;
                        nodes.Add(new ConfigNodeInfo(field.Name, GetTypeName(field.Type), key, fieldSerializer));
                    }
                    break;
                case IPropertySymbol property when !property.IsStatic && property.SetMethod != null:
                    if (TryGetConfigNode(property, out var propertyKey, out var propertySerializer))
                    {
                        var key = propertyKey.Length == 0 ? property.Name : propertyKey;
                        nodes.Add(new ConfigNodeInfo(property.Name, GetTypeName(property.Type), key, propertySerializer));
                    }
                    break;
            }
        }

        return nodes;
    }

    private static ConfigInfo GetConfigInfo(ISymbol symbol)
    {
        foreach (var attr in symbol.GetAttributes())
        {
            if (attr.AttributeClass?.Name != "ConfigAttribute")
                continue;

            var fileName = "";
            var backendType = "";
            var version = 1;
            foreach (var arg in attr.ConstructorArguments)
            {
                if (arg.Value is string configuredFileName)
                    fileName = configuredFileName;
                else if (arg.Value is INamedTypeSymbol backendSymbol)
                    backendType = GetTypeName(backendSymbol);
                else if (arg.Value is int configuredVersion)
                    version = configuredVersion;
            }

            foreach (var namedArg in attr.NamedArguments)
            {
                if (namedArg.Key == "Version" && namedArg.Value.Value is int namedVersion)
                    version = namedVersion;
            }

            return new ConfigInfo(fileName, backendType, version);
        }

        return new ConfigInfo("", "", 1);
    }

    private static bool TryGetConfigNode(ISymbol symbol, out string key, out string serializerType)
    {
        foreach (var attr in symbol.GetAttributes())
        {
            if (attr.AttributeClass?.Name != "ConfigNodeAttribute")
                continue;

            key = "";
            serializerType = "";
            foreach (var arg in attr.ConstructorArguments)
            {
                if (arg.Value is string configuredKey)
                    key = configuredKey;
                else if (arg.Value is INamedTypeSymbol serializerSymbol)
                    serializerType = GetTypeName(serializerSymbol);
            }

            return true;
        }

        key = "";
        serializerType = "";
        return false;
    }

    private static string GetTypeName(ITypeSymbol type)
        => type.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat);

    private static bool HasAttribute(ISymbol symbol, string attrName)
    {
        return symbol.GetAttributes().Any(attr => attr.AttributeClass?.Name == attrName);
    }

    private static string EscapeIdentifier(string value)
    {
        return SyntaxFacts.GetKeywordKind(value) == SyntaxKind.None
            ? value
            : "@" + value;
    }

    private static string EscapeString(string value)
    {
        return value.Replace("\\", "\\\\").Replace("\"", "\\\"");
    }

}
